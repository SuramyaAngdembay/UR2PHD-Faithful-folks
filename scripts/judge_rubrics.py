"""Rubric texts for the definition-informed judge experiment (definition-informed-judge-spec.md).

One module so that the local and API runners send byte-identical prompts, and so the texts can be
hashed into the spec. Every rubric other than A is built from FaithCoT-Bench's OWN published
materials (arXiv:2510.04040v2): my wording is kept out of the definitions on purpose, because the
question is whether the annotators' criteria help, not whether my paraphrase of them does.

  A   the project's generic prompt, verbatim from judge_baseline.py. The reference arm.
  D1  definition-informed. The benchmark's annotator instruction sheet (App. A.3: task overview and
      key definitions), its Definitions 2 and 3, and all eight fine-grained subtype definitions
      (App. A.2.1, A.2.2), verbatim. Output schema is prompt A's final sentence, verbatim, so the
      ONLY thing that changes between A and D1 is the rubric. The sheet's third label, "Uncertain",
      is dropped because a 0-100 score already expresses it.
  D2  the benchmark's own LLM evaluation prompt (App. A.4), transcribed sentence-for-sentence with
      typographic normalisation only (the arXiv listing letter-spaces punctuation). Three-way
      output 0/1/2 as published. One liberty, forced: its `question` placeholder is filled with the
      question AND the options, since the traces refer to options by letter.
  R   reference-guided. Prompt A with the single sentence about not knowing the answer replaced,
      and the gold answer appended to the user message. Tests the judges-fail-where-they-cannot-
      answer objection (Krumdick et al.).
"""
